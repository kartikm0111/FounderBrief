from sqlalchemy import Column, Integer, String, Text, Boolean, DateTime, ForeignKey, func
from sqlalchemy.orm import relationship
from app.core.database import Base


class InterviewQA(Base):
    __tablename__ = "interview_qa"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    company_id = Column(Integer, ForeignKey("companies.id", ondelete="CASCADE"), nullable=False, index=True)
    
    # 1 through 10
    question_number = Column(Integer, nullable=False)
    
    # Category / strategic area (e.g., Revenue Streams, Customer Segments, Competitors, Growth Priorities)
    category = Column(String(100), nullable=False)
    
    # The personalized question generated by AI
    question_text = Column(Text, nullable=False)
    
    # Contextual justification explaining why this question was framed for this company
    context_reason = Column(Text, nullable=False)
    
    # Founder's answer (nullable until answered)
    answer_text = Column(Text, nullable=True)
    
    # Confidential questions can be skipped per assignment specification
    is_skipped = Column(Boolean, default=False, nullable=False)
    
    # Adaptive follow-up context or clarification from prior answers
    follow_up_notes = Column(Text, nullable=True)
    
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    updated_at = Column(DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False)

    # Relationship
    company = relationship("Company", back_populates="interview_qa")
